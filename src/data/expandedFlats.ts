function buildFlatGallery(
  flatName: string,
  heroSrc: string,
  city: City,
  bedrooms: Flat['bedrooms'],
  seedIndex: number
): GalleryImageItem[] {
  const floorplanSrc =
    bedrooms === '1 BHK' || bedrooms === '2 BHK'
      ? '/src/assets/images/floorplan_2bhk_modern_1795170525120.jpg'
      : '/src/assets/images/floorplan_3bhk_luxury_1795170526504.jpg';

  const bedroomImg = INTERIOR_ROTATION[seedIndex % INTERIOR_ROTATION.length];
  const kitchenImg = INTERIOR_ROTATION[(seedIndex + 1) % INTERIOR_ROTATION.length];
  const lobbyImg = INTERIOR_ROTATION[(seedIndex + 2) % INTERIOR_ROTATION.length];
  const clubImg = INTERIOR_ROTATION[(seedIndex + 3) % INTERIOR_ROTATION.length];
  const terraceImg = INTERIOR_ROTATION[(seedIndex + 4) % INTERIOR_ROTATION.length];

  return [
    { title: `${flatName} Architectural Elevation`, category: 'Exterior', src: heroSrc },
    { title: 'Master Bedroom & Private Balcony', category: 'Master Suite', src: bedroomImg },
    { title: 'Open Modular Kitchen & Dining', category: 'Kitchen & Dining', src: kitchenImg },
    { title: 'Double-Height Arrival Concierge Lobby', category: 'Arrival Lobby', src: lobbyImg },
    { title: 'Clubhouse Pool & Cabana Deck', category: 'Clubhouse', src: clubImg },
    { title: 'Landscaped Sky Terrace Lounge', category: 'Outdoor Deck', src: terraceImg },
    { title: `${bedrooms} Audited CAD Blueprint`, category: 'Floor Plan', src: floorplanSrc },
    { title: `${city} Micro-Market Transit Map`, category: 'Cartography', src: CITY_MAP_BY_CITY[city] },
  ];
}

